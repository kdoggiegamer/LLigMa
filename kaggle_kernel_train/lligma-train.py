"""Train LLigMa Small on the Italian corpus, then measure whether it learned.

Platform constraints this kernel is built around:

* A GPU session dies at 12 hours, so training stops on a wall clock
  (`--max-hours`) and always leaves a resumable checkpoint behind.
* Committed output is capped at 20 GB. Checkpoints are ~2.3 GB in bf16, so only
  the newest two are kept (`--keep-checkpoints`).
* Resume across sessions needs the previous checkpoint. The previous version of
  this kernel is mounted as a kernel source, so its output reappears under
  /kaggle/input without any download-and-reupload step.

The verdict at the end is measured, not asserted: perplexity of the trained model
on held-out Italian against the same architecture at random initialisation, plus
text actually generated by the trained weights.
"""

import importlib.util
import json
import os
import subprocess
import sys
from pathlib import Path

import numpy as np
import torch

WORK = Path("/kaggle/working")
RUN = WORK / "run"
SEQUENCE_LENGTH = 512
BATCH_SIZE = 4
GRAD_ACCUM = 4
MAX_HOURS = 1.5
SAVE_EVERY = 200
EVAL_STEPS = 200
LEARNING_RATE = 3e-4
KEEP_CHECKPOINTS = 2


def find_input(slug):
    direct = Path(f"/kaggle/input/{slug}")
    if direct.is_dir():
        return direct
    for candidate in Path("/kaggle/input").glob(f"*/{slug}"):
        if candidate.is_dir():
            return candidate
    for candidate in Path("/kaggle/input").rglob(slug):
        if candidate.is_dir():
            return candidate
    raise FileNotFoundError(f"{slug} not mounted under /kaggle/input")


def find_repo():
    for candidate in Path("/kaggle/input").rglob("requirements.txt"):
        if (candidate.parent / "lligma").is_dir():
            return candidate.parent
    raise FileNotFoundError("LLigMa code dataset not found")


def install_dependencies(repo):
    requirements = (repo / "requirements.txt").read_text(encoding="utf-8").splitlines()
    packages = [line.strip() for line in requirements if line.strip() and not line.strip().lower().startswith("torch")]
    print("installing:", packages, flush=True)
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", *packages], check=True)
    import transformers
    print("torch", torch.__version__, "| transformers", transformers.__version__, flush=True)


def latest_checkpoint(*directories):
    best, best_step = None, -1
    for directory in directories:
        if not directory or not Path(directory).is_dir():
            continue
        for path in sorted(Path(directory).glob("checkpoint-*.pt")):
            try:
                step = int(path.stem.split("-")[1])
            except (IndexError, ValueError):
                continue
            if step > best_step:
                best, best_step = path, step
    return best, best_step


def load_model(repo, config_path, vocab_size):
    sys.path.insert(0, str(repo))
    from lligma.model import LLigMaConfig, LLigMaForCausalLM
    import yaml

    values = yaml.safe_load(Path(config_path).read_text(encoding="utf-8")) or {}
    values.pop("model_type", None)
    values["vocab_size"] = vocab_size
    values["max_position_embeddings"] = max(values.get("max_position_embeddings", 0), SEQUENCE_LENGTH)
    values["use_cache"] = True
    config = LLigMaConfig(**values)
    model = LLigMaForCausalLM(config)
    return config, model


def evaluate_perplexity(model, tokens_path, batches=40, batch_size=2):
    tokens = np.memmap(tokens_path, dtype=np.uint16, mode="r")
    blocks = len(tokens) // SEQUENCE_LENGTH
    if not blocks:
        raise ValueError("validation token file is too short")
    generator = torch.Generator().manual_seed(0)
    picks = torch.randint(0, blocks, (min(batches, blocks),), generator=generator)
    model.eval()
    total, counted = 0.0, 0
    with torch.no_grad():
        for index in picks.tolist():
            start = index * SEQUENCE_LENGTH
            block = np.asarray(tokens[start:start + SEQUENCE_LENGTH], dtype=np.int64)
            input_ids = torch.from_numpy(block).unsqueeze(0).to("cuda")
            loss = model(input_ids=input_ids, labels=input_ids, use_cache=False).loss
            total += loss.item()
            counted += 1
    mean = total / max(counted, 1)
    return mean, float(np.exp(min(mean, 20.0)))


def generate_sample(model, prompt_ids, new_tokens=48):
    model.eval()
    generated = prompt_ids
    past = None
    with torch.no_grad():
        for _ in range(new_tokens):
            if past is None:
                outputs = model(input_ids=generated, use_cache=True)
            else:
                outputs = model(input_ids=generated[:, -1:], past_key_values=past,
                                attention_mask=torch.ones(1, generated.shape[1], dtype=torch.long, device="cuda"),
                                use_cache=True)
            past = outputs.past_key_values
            next_token = outputs.logits[:, -1].argmax(dim=-1, keepdim=True)
            generated = torch.cat([generated, next_token], dim=1)
    return generated


def main():
    repo = find_repo()
    print(f"code from {repo}", flush=True)
    install_dependencies(repo)

    prep = find_input("lligma-prep")
    corpus_tokens = prep / "tokens" / "train.bin"
    valid_tokens = prep / "tokens" / "valid.bin"
    tokenizer_dir = prep / "tokenizer"
    stats = json.loads((prep / "stats.json").read_text(encoding="utf-8")) if (prep / "stats.json").is_file() else {}
    print(f"prep from {prep} | stats: {json.dumps(stats)}", flush=True)
    print(f"cuda: {torch.cuda.is_available()} | {torch.cuda.get_device_name(0) if torch.cuda.is_available() else 'none'}",
          flush=True)

    config_path = repo / "configs" / "lligma_3_0_small.yaml"
    # Resume across sessions: a follow-up kernel mounts the previous training
    # kernel's committed output, so no checkpoint needs downloading or reuploading.
    sources = []
    try:
        sources.append(find_input("lligma-train") / "run")
    except FileNotFoundError:
        print("no previous training kernel mounted", flush=True)
    previous, previous_step = latest_checkpoint(*sources, RUN)
    print(f"resume checkpoint: {previous} (step {previous_step})", flush=True)

    # Baseline: the same architecture at random initialisation, same seed the
    # trainer uses, evaluated on the same held-out blocks.
    from transformers import AutoTokenizer

    vocab_size = len(AutoTokenizer.from_pretrained(str(tokenizer_dir), use_fast=True))
    print(f"vocabulary: {vocab_size}", flush=True)
    torch.manual_seed(42)
    _, baseline = load_model(repo, config_path, vocab_size)
    baseline.to("cuda").to(dtype=torch.bfloat16)
    base_loss, base_ppl = evaluate_perplexity(baseline, valid_tokens)
    print(f"BASELINE random-init held-out loss={base_loss:.4f} perplexity={base_ppl:.1f}", flush=True)
    del baseline
    torch.cuda.empty_cache()

    command = [
        sys.executable, str(repo / "scripts" / "train.py"),
        "--config", str(config_path),
        "--tokens-file", str(corpus_tokens),
        "--validation-tokens-file", str(valid_tokens),
        "--tokenizer", str(tokenizer_dir),
        "--output-dir", str(RUN),
        "--sequence-length", str(SEQUENCE_LENGTH),
        "--batch-size", str(BATCH_SIZE),
        "--gradient-accumulation-steps", str(GRAD_ACCUM),
        "--max-steps", "1000000",
        "--learning-rate", str(LEARNING_RATE),
        "--weight-decay", "0.1",
        "--eval-steps", str(EVAL_STEPS),
        "--max-eval-examples", "64",
        "--save-every", str(SAVE_EVERY),
        "--keep-checkpoints", str(KEEP_CHECKPOINTS),
        "--max-hours", str(MAX_HOURS),
        "--bf16",
        "--device", "cuda",
    ]
    if previous is not None:
        command += ["--resume-from", str(previous)]
    print("RUN " + " ".join(command), flush=True)
    subprocess.run(command, check=True)

    # Verdict, measured on the trained weights. save_pretrained writes
    # safetensors when the package is available and a .bin otherwise.
    sys.path.insert(0, str(repo))
    from lligma.model import LLigMaConfig, LLigMaForCausalLM

    tokenizer = AutoTokenizer.from_pretrained(str(RUN), use_fast=True)
    config = LLigMaConfig.from_pretrained(str(RUN))
    model = LLigMaForCausalLM(config)
    # Load from the checkpoint: it holds the whole state dict, including the
    # tied lm_head that save_pretrained omits from the public weights file.
    checkpoint, _ = latest_checkpoint(RUN)
    if checkpoint is not None:
        state = torch.load(checkpoint, map_location="cpu")["model"]
        model.load_state_dict(state)
    else:
        from safetensors.torch import load_file
        model.load_state_dict(load_file(str(RUN / "model.safetensors")))
    model = model.to("cuda").to(dtype=torch.bfloat16)
    loss, perplexity = evaluate_perplexity(model, valid_tokens, batches=40)
    print(f"TRAINED held-out loss={loss:.4f} perplexity={perplexity:.1f}", flush=True)
    print(f"BASELINE held-out perplexity={base_ppl:.1f}", flush=True)
    print(f"verdict: {base_ppl / max(perplexity, 1e-9):.2f}x better than random init", flush=True)

    for prompt in ["L'Italia è", "La storia di Roma", "Nel 1945 l'Europa"]:
        ids = tokenizer(prompt, return_tensors="pt", add_special_tokens=False)["input_ids"].to("cuda")
        generated = generate_sample(model, ids)
        print("SAMPLE " + repr(prompt) + " -> " + repr(tokenizer.decode(generated[0], skip_special_tokens=True)),
              flush=True)

    summary = {
        "baseline_loss": base_loss, "baseline_perplexity": base_ppl,
        "trained_loss": loss, "trained_perplexity": perplexity,
        "improvement_x": base_ppl / max(perplexity, 1e-9),
        "max_hours": MAX_HOURS, "sequence_length": SEQUENCE_LENGTH,
        "batch_size": BATCH_SIZE, "grad_accum": GRAD_ACCUM, "learning_rate": LEARNING_RATE,
    }
    (WORK / "verdict.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print("VERDICT " + json.dumps(summary), flush=True)
    print("TRAIN DONE", flush=True)


if __name__ == "__main__":
    main()
